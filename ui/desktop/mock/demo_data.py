def populate_demo_state(state: AppState) -> None:
    """Fills an AppState instance with rich mock data for UI testing."""
    state.update_system_status(
        msc_detected=True,
        msc_loader_present=True,
        mods_dir="/home/souza/My Summer Car/Mods",
        nexus_authenticated=True,
        nexus_user="Matheushopi",
        nexus_tier="Supporter",
        browser_detected="Brave",
        browser_tabs_count=15,
        engine_state="Idle",
    )
    state.set_mods(SAMPLE_MODS)
    state.set_downloads(SAMPLE_DOWNLOADS)
    state.add_activity("Nexus authenticated: Matheushopi (Supporter)", level="SUCCESS")
    state.add_activity("My Summer Car and MSCLoader detected in /home/souza/My Summer Car/Mods", level="INFO")
    state.add_activity("Scanned 23 installed mods (20 managed, 3 unmanaged)", level="INFO")
    state.add_activity("Detected 15 active Nexus mod tabs in Brave browser", level="INFO")
    state.add_activity("MSCLoader Mod #147 satisfied by system environment", level="INFO")
